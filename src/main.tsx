import { StrictMode } from 'react';
import { createRoot } from 'react-dom/client';
import { BrowserRouter } from 'react-router-dom';
import { HelmetProvider } from 'react-helmet-async';
import App from './App';
import './index.css';

// createRoot (not hydrateRoot) on purpose: the prerendered HTML written by
// scripts/prerender.mjs is static markup, not a React SSR payload. React
// simply re-renders over it, which avoids hydration-mismatch errors.
createRoot(document.getElementById('root')!).render(
  <StrictMode>
    <HelmetProvider>
      <BrowserRouter>
        <App />
      </BrowserRouter>
    </HelmetProvider>
  </StrictMode>,
);
